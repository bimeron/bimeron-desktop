inline QString geoSiteName(const QString &id) {
    const auto it = geoSiteEntries().constFind(id);
    return it == geoSiteEntries().cend() ? QString{} : QObject::tr(it->name);
}
inline QString geoSiteSearchText(const QString &id) {
    static const QJsonObject russian = [] {
        QFile file(":/translations/ru.json");
        return file.open(QIODevice::ReadOnly) ? QJsonDocument::fromJson(file.readAll()).object() : QJsonObject{};
    }();
    const auto it = geoSiteEntries().constFind(id);
    if (it == geoSiteEntries().cend()) return id;
    const QString name = QString::fromUtf8(it->name);
    QString search = id + '\n' + name + '\n' + russian.value(name).toString();
    const QString section = geoSiteSections().at(it->section);
    search += '\n' + section + '\n' + russian.value(section).toString();
    if (it->topic) for (const auto &topic : geoSiteTopics()) {
        if (QString::fromUtf8(topic.id) != QString::fromUtf8(it->topic)) continue;
        const QString label = QString::fromUtf8(topic.name);
        search += '\n' + label + '\n' + russian.value(label).toString();
        break;
    }
    return search;
}
